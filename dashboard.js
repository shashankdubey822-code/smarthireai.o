// ── KPI Rendering ────────────────────────────────────────────
function renderKPIs(data) {
    animateValue(document.getElementById("kpiTotalValue"), data.length);
    animateValue(document.getElementById("kpiCompaniesValue"), uniqueValues(data, "company").length);
    animateValue(document.getElementById("kpiRolesValue"), uniqueValues(data, "role").length);

    // Top seniority
    const seniorityMap = countBy(data.filter(d => d.seniority), "seniority");
    const sorted = Object.entries(seniorityMap).sort((a, b) => b[1] - a[1]);
    document.getElementById("kpiSeniorityValue").textContent = sorted.length ? sorted[0][0] : "—";

    // Update additional KPIs
    const avgCtcEl = document.getElementById("kpiAvgCtcValue");
    if (avgCtcEl) {
        const ctcValues = data.map(d => parseFloat((d.ctc || "").replace(/[^\d.]/g, ""))).filter(v => !isNaN(v) && v > 0);
        avgCtcEl.textContent = ctcValues.length ? `₹${(ctcValues.reduce((a, b) => a + b, 0) / ctcValues.length).toFixed(1)}L` : "—";
    }

    const locationsEl = document.getElementById("kpiLocationsValue");
    if (locationsEl) {
        const locations = uniqueValues(data.filter(d => d.location), "location");
        animateValue(locationsEl, locations.length);
    }
}

