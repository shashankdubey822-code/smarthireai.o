function sortData(data, key, asc) {
    return [...data].sort((a, b) => {
        const va = (a[key] || "").toLowerCase();
        const vb = (b[key] || "").toLowerCase();
        return asc ? va.localeCompare(vb) : vb.localeCompare(va);
    });
}

function getFilteredData() {
    const query = (document.getElementById("dashSearch").value || "").toLowerCase();
    const senFilter = document.getElementById("seniorityFilter").value;
    const schoolFilter = document.getElementById("schoolFilter") ? document.getElementById("schoolFilter").value : "";
    let filtered = SHEET_DATA;
    if (query) {
        filtered = filtered.filter(d =>
            d.company.toLowerCase().includes(query) ||
            d.role.toLowerCase().includes(query) ||
            (d.seniority || "").toLowerCase().includes(query) ||
            (d.location || "").toLowerCase().includes(query) ||
            (d.ctc || "").toLowerCase().includes(query) ||
            (d.school || "").toLowerCase().includes(query)
        );
    }
    if (senFilter) {
        filtered = filtered.filter(d => (d.seniority || "Unknown") === senFilter);
    }
    if (schoolFilter) {
        filtered = filtered.filter(d => {
            if ((d.school || "Unknown") === schoolFilter) return true;
            const textToScan = `${d.eligibility || ""} ${d.role || ""}`;
            const courses = extractCoursesHeuristically(textToScan);
            for (const course of courses) {
                if (classifyCourseToSchool(course) === schoolFilter) return true;
            }
            return false;
        });
    }
    return sortData(filtered, currentSort.key, currentSort.asc);
}

