// ── Google Sheets Fetch (via backend proxy to bypass Google's CDN cache) ─────
// Previously we fetched gviz/tq directly from the browser.  Google's CDN caches
// those responses for several minutes — so deleting rows from the sheet would
// not immediately reflect in the dashboard.
// Now we route through our own backend (/api/sheet-data) which:
//   1. Makes a server-side request with Cache-Control: no-cache headers
//   2. Returns the response with Cache-Control: no-store so the browser also
//      never caches it
// This guarantees that what the sheet contains RIGHT NOW is what we display.
async function fetchSheetData() {
    // Use a random cache-buster on our own proxy too, just to be safe
    const bust = `${Date.now()}_${Math.random().toString(36).slice(2)}`;
    const url  = `/api/sheet-data?gid=${SHEET_CONFIG.gid}&_=${bust}`;

    const response = await fetch(url, {
        cache: "no-store",   // Instruct the browser fetch cache to skip storage
        headers: {
            "Cache-Control": "no-cache",
            "Pragma":        "no-cache",
        },
    });

    if (!response.ok) {
        const errJson = await response.json().catch(() => ({}));
        throw new Error(errJson.error || `Proxy returned HTTP ${response.status}. Check that the server is running.`);
    }

    const json = await response.json();

    if (json.status === "error") {
        throw new Error(json.errors?.map(e => e.message).join(", ") || "Google Sheets API error");
    }

    const rows = json.table?.rows || [];
    const data = [];

    for (const row of rows) {
        const cells = row.c || [];
        const getValue = (idx) => {
            const cell = cells[idx];
            if (!cell) return "";
            // Use formatted value (f) if available, otherwise raw value (v)
            return (cell.f || cell.v || "").toString().trim();
        };

        const timestamp = getValue(COL_MAP.timestamp);
        const company   = getValue(COL_MAP.company);
        if (!company) continue; // Skip empty rows

        const roleVal = getValue(COL_MAP.role);
        const skillsVal = getValue(COL_MAP.skills);
        const eligibilityVal = getValue(COL_MAP.eligibility);
        const schoolValRaw = getValue(COL_MAP.school);
        const schoolVal = schoolValRaw || classifySchoolHeuristically(
            { role: roleVal, skills: skillsVal },
            roleVal + " " + skillsVal + " " + eligibilityVal
        );

        data.push({
            timestamp,
            company,
            cycle: getValue(COL_MAP.cycle),
            companyCycle: getValue(COL_MAP.companyCycle),
            role: roleVal,
            seniority: getValue(COL_MAP.seniority),
            location: getValue(COL_MAP.location),
            ctc: getValue(COL_MAP.ctc),
            eligibility: eligibilityVal,
            skills: skillsVal,
            tools: getValue(COL_MAP.tools),
            complexity: getValue(COL_MAP.complexity),
            generatedBy: getValue(COL_MAP.generatedBy),
            school: schoolVal,
        });
    }

    return { data, table: json.table || { cols: [], rows: [] }, _needsRedeploy: json._needsRedeploy || false, _source: json._source || "unknown" };
}


// Simple hash to detect data changes.
// IMPORTANT: empty arrays must NOT hash to "" — that equals the sentinel
// and would suppress the very first render when the sheet is empty.
function hashData(data) {
    if (data.length === 0) return "__EMPTY__";
    return data.map(d => `${d.timestamp}|${d.company}|${d.role}`).join("##");
}

// ── Helpers ──────────────────────────────────────────────────
function countBy(arr, key) {
    const map = {};
    arr.forEach(item => {
        const val = (item[key] || "Unknown").trim();
        map[val] = (map[val] || 0) + 1;
    });
    return map;
}

function uniqueValues(arr, key) {
    return [...new Set(arr.map(i => (i[key] || "Unknown").trim()))];
}

function classifyCourseToSchool(courseName) {
    const c = courseName.toLowerCase().trim();

    // School of Engineering (SOE)
    if (/\b(b\.?tech|m\.?tech|b\.?e\.?|m\.?e\.?|b\.?c\.?a\.?|m\.?c\.?a\.?|cse|computer|software|engineering|devops|cloud|it|information\s*technology|ece|electronics|mechanical|civil|electrical|aerospace|data\s*engineering|b\.?sc|m\.?sc|science|math|statistics|stat|data\s*science|data\s*analyst|llb|llm|law|legal|ba|ma|arts|design|humanities|psychology)\b/i.test(c)) {
        // Science/Law/Humanities courses default to SOE unless business pattern matches
        if (/\b(mba|bba|pgdm|b\.?com|m\.?com|finance|management|marketing|business|commerce|accounting|hr|recruiting|sales|bms)\b/i.test(c)) {
            return "School of Business (SOB)";
        }
        return "School of Engineering (SOE)";
    }

    // School of Business (SOB)
    if (/\b(mba|bba|pgdm|b\.?com|m\.?com|finance|management|marketing|business|commerce|accounting|hr|recruiting|sales|bms)\b/i.test(c)) {
        return "School of Business (SOB)";
    }

    // Fallback keyword matching
    if (/business|commerce|manag|market|finance|sales|hr\b/i.test(c)) return "School of Business (SOB)";

    return "School of Engineering (SOE)"; // Safe default
}

function extractCoursesHeuristically(text) {
    if (!text) return [];
    const coursesFound = new Set();

    const pattern = /\b(b\.?\s*tech|m\.?\s*tech|b\.?\s*e|m\.?\s*e|b\.?\s*c\.?\s*a|m\.?\s*c\.?\s*a|m\.?\s*b\.?\s*a|b\.?\s*b\.?\s*a|b\.?\s*com|m\.?\s*com|b\.?\s*sc|m\.?\s*sc|ph\.?\s*d|l\.?\s*l\.?\s*b|l\.?\s*l\.?\s*m|b\.?\s*a|m\.?\s*a|pgdm)\b/gi;
    const branchPattern = /\b(b\.?\s*tech|m\.?\s*tech|b\.?\s*e|m\.?\s*e|mba|mca|bca|bsc|msc|bba)\b\s*\(?[a-z\s]{2,10}\)?/gi;

    let match;
    while ((match = branchPattern.exec(text)) !== null) {
        coursesFound.add(match[0].trim());
    }

    while ((match = pattern.exec(text)) !== null) {
        const course = match[1].trim();
        let normalized = course.replace(/\s+/g, "").toUpperCase();

        if (normalized.startsWith("B") && normalized.endsWith("TECH")) normalized = "B.Tech";
        else if (normalized.startsWith("M") && normalized.endsWith("TECH")) normalized = "M.Tech";
        else if (normalized === "MBA") normalized = "MBA";
        else if (normalized === "MCA") normalized = "MCA";
        else if (normalized === "BCA") normalized = "BCA";
        else if (normalized === "BE") normalized = "B.E.";
        else if (normalized === "ME") normalized = "M.E.";
        else if (normalized.startsWith("B") && normalized.endsWith("SC")) normalized = "B.Sc";
        else if (normalized.startsWith("M") && normalized.endsWith("SC")) normalized = "M.Sc";
        else if (normalized === "BBA") normalized = "BBA";
        else if (normalized.startsWith("B") && normalized.endsWith("COM")) normalized = "B.Com";
        else if (normalized.startsWith("M") && normalized.endsWith("COM")) normalized = "M.Com";
        else if (normalized === "PHD" || normalized === "PH.D") normalized = "PhD";
        else if (normalized === "LLB") normalized = "LLB";
        else if (normalized === "LLM") normalized = "LLM";
        else if (normalized === "BA") normalized = "BA";
        else if (normalized === "MA") normalized = "MA";
        else if (normalized === "PGDM") normalized = "PGDM";

        let alreadyExists = false;
        for (const existing of coursesFound) {
            if (existing.replace(/\s+/g, "").toUpperCase().includes(normalized.replace(/\./g, "").toUpperCase())) {
                alreadyExists = true;
                break;
            }
        }
        if (!alreadyExists) {
            coursesFound.add(normalized);
        }
    }

    return Array.from(coursesFound);
}

function renderSchoolBadges(primarySchool, eligibility, role) {
    const schools = new Set();
    
    if (primarySchool && primarySchool.includes("School")) {
        schools.add(primarySchool);
    }

    const textToScan = `${eligibility || ""} ${role || ""}`;
    const courses = extractCoursesHeuristically(textToScan);
    for (const course of courses) {
        schools.add(classifyCourseToSchool(course));
    }

    if (schools.size === 0) {
        schools.add(primarySchool || "School of Engineering (SOE)");
    }

    return Array.from(schools).map(school => {
        const cls = school.toLowerCase().replace(/[^a-z0-9]/g, '_');
        return `<span class="school-badge ${cls}" style="margin: 2px 4px 2px 0;">${school}</span>`;
    }).join(" ");
}

function classifySchoolHeuristically(result, jdText) {
    // Only SOE and SOB are active schools.
    const role   = (result.role || "").toLowerCase().trim();
    const cat    = (result.category || result.cat || "").toLowerCase().trim();
    const skills = (result.skills || "").toLowerCase();
    const tools  = (result.tools || "").toLowerCase();
    const combined = `${role} ${cat} ${skills} ${tools}`;

    // ── SOB — School of Business ─────────────────────────────
    const sobRoleTerms = [
        "business analyst","product manager","marketing","sales",
        "finance","accounting","accountant","operations manager",
        "supply chain","logistics","brand manager","growth",
        "strategy","management consultant","investment","equity",
        "trading","audit","tax","treasury","hr manager",
        "human resource","recruiter","talent acquisition",
        "customer success","account manager","business development",
        "ceo","cfo","coo","management trainee","trainee"
    ];
    const sobQualTerms = ["mba","bba","bcom","b.com","cfa","cpa","pgdm"];
    const sobCatTerms = [
        "business","marketing","sales","finance","management",
        "operations","consulting","strategy","human resources"
    ];
    if (
        sobRoleTerms.some(k => role.includes(k)) ||
        sobQualTerms.some(k => combined.includes(k)) ||
        sobCatTerms.some(k => cat.includes(k))
    ) return "School of Business (SOB)";

    // ── SOE — School of Engineering (default for tech, science, law, arts) ─
    return "School of Engineering (SOE)";
}


function formatDate(ts) {
    try {
        if (!ts) return "";
        let d;
        if (ts.startsWith("Date(")) {
            const matches = ts.match(/\d+/g);
            if (matches && matches.length >= 3) {
                const y = parseInt(matches[0]);
                const m = parseInt(matches[1]);
                const day = parseInt(matches[2]);
                const h = parseInt(matches[3] || "0");
                const min = parseInt(matches[4] || "0");
                const s = parseInt(matches[5] || "0");
                d = new Date(y, m, day, h, min, s);
            }
        } else if (ts.includes("/")) {
            const [datePart, timePart] = ts.split(" ");
            const parts = datePart.split("/");
            if (parts.length === 3) {
                // Handle dd/MM/yyyy format
                const [day, month, year] = parts;
                d = new Date(parseInt(year), parseInt(month) - 1, parseInt(day));
                if (timePart) {
                    const [h, m, s] = timePart.split(":");
                    d.setHours(parseInt(h) || 0, parseInt(m) || 0, parseInt(s) || 0);
                }
            }
        } else {
            d = new Date(ts.replace(" ", "T"));
        }
        if (!d || isNaN(d.getTime())) return ts;
        return d.toLocaleDateString("en-IN", {
            timeZone: "Asia/Kolkata",
            day: "2-digit",
            month: "short",
            year: "numeric"
        });
    } catch { return ts; }
}

