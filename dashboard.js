function showSchoolSpotlight(school) {
    const panel    = document.getElementById("schoolSpotlight");
    const meta     = SCHOOL_META[school] || { theme:"soe-theme", icon:"school", color:"#6366f1", accent:"rgba(99,102,241,", desc:"" };
    const filtered = SHEET_DATA.filter(d => (d.school || "") === school);

    if (!panel) return;

    // Apply theme colour
    panel.className = `school-spotlight ${meta.theme}`;

    // Update header
    document.getElementById("spotlightIcon").textContent = meta.icon;
    document.getElementById("spotlightName").textContent = school;
    document.getElementById("spotlightSubtitle").textContent = meta.desc;

    // KPIs
    const companies   = new Set(filtered.map(d => d.company).filter(Boolean));
    const roles       = new Set(filtered.map(d => d.role).filter(Boolean));
    const senMap      = countBy(filtered, "seniority");
    const topSen      = Object.entries(senMap).sort((a,b) => b[1]-a[1])[0]?.[0] || "—";
    const share       = SHEET_DATA.length ? Math.round(filtered.length / SHEET_DATA.length * 100) : 0;

    // ── Smart CTC parser — handles INR raw, LPA, monthly, ranges ──
    function parseCTCtoLPA(raw) {
        if (!raw) return null;
        const s = raw.replace(/,/g, ""); // remove commas from "4,82,020"

        // Extract all numbers from the string
        const nums = [...s.matchAll(/[\d]+(?:\.\d+)?/g)].map(m => parseFloat(m[0]));
        if (!nums.length) return null;

        // Pick the first meaningful number (skip tiny ones like "6.5" prefix from "6.5 LPA" contexts)
        let val = nums[0];

        // If string says "per month" / "monthly" → annualise × 12
        const isMonthly = /per\s*month|monthly|p\.?m\.?/i.test(s);
        if (isMonthly) val = val * 12;

        // Decide unit: if value >= 10000 it's in ₹ → convert to LPA (÷ 100000)
        // if < 1000 it's already LPA; values 1000–9999 are ambiguous — skip
        if (val >= 10000) {
            val = val / 100000; // ₹ → LPA
        } else if (val >= 1000) {
            return null; // ambiguous — skip
        }
        // Sanity bounds: CTC should be 0.5–200 LPA
        if (val < 0.5 || val > 200) return null;
        return val;
    }

    const ctcNums = filtered.map(d => parseCTCtoLPA(d.ctc)).filter(n => n !== null);
    const avgCtcVal = ctcNums.length
        ? ctcNums.reduce((a, b) => a + b, 0) / ctcNums.length
        : null;
    const avgCtc = avgCtcVal !== null
        ? avgCtcVal.toFixed(1) + " LPA"
        : "—";


    // ── Highest Package ────────────────────────────────────────
    const highestCtc = ctcNums.length ? Math.max(...ctcNums).toFixed(1) + " LPA" : "—";

    document.getElementById("spTotal").textContent        = filtered.length;
    document.getElementById("spCompanies").textContent    = companies.size;
    document.getElementById("spRoles").textContent        = roles.size;
    document.getElementById("spAvgCtc").textContent       = avgCtc;
    document.getElementById("spHighestCtc").textContent   = highestCtc;
    document.getElementById("spTopSeniority").textContent = topSen;
    document.getElementById("spShare").textContent        = share + "%";

    // Render 5 spotlight charts
    destroySpotlightCharts();
    renderSpotlightCharts(filtered, meta);

    // Show with animation
    panel.classList.remove("hidden");
    panel.scrollIntoView({ behavior: "smooth", block: "nearest" });
}

