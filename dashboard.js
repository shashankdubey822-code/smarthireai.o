// ── Initialize Dashboard ──────────────────────────────
async function initDashboard() {
    updateAutoRefreshUI();
    initSchoolPillListeners();
    await loadDashboardData(true);
    startPolling();

    // ── Clear All Data button ──────────────────────────
    const clearBtn = document.getElementById('clearDashboard');
    if (clearBtn) {
        clearBtn.addEventListener('click', async () => {
            const confirmed = confirm(
                '⚠️ Clear ALL data from the Google Sheet?\n\n' +
                'This will permanently delete every row from the sheet ' +
                'and reset the dashboard to zero. This cannot be undone.'
            );
            if (!confirmed) return;

            clearBtn.disabled = true;
            clearBtn.textContent = 'Clearing…';

            try {
                const res  = await fetch('/api/clear-sheet', { method: 'POST' });
                const json = await res.json();

                if (json.success) {
                    // Immediately wipe local state and re-render empty dashboard
                    SHEET_DATA = [];
                    lastDataHash = '__UNINITIALISED__';
                    renderDashboard([], false);
                    renderLiveSheet({ cols: [], rows: [] });
                    showRedeployWarning(false);
                    alert('✅ Sheet cleared! ' + (json.rowsDeleted || 0) + ' rows deleted.');
                } else {
                    // clearSheet not yet deployed — guide the user
                    alert(
                        '⚠️ Could not clear automatically.\n\n' +
                        'Please do ONE of these:\n' +
                        '1. In the Apps Script editor, run the clearAllData() function (no deploy needed)\n' +
                        '2. OR open Google Sheets → select rows 2 onward → right-click → Delete rows'
                    );
                }
            } catch (err) {
                alert('Error: ' + err.message);
            } finally {
                clearBtn.disabled = false;
                clearBtn.innerHTML = '<span class="material-symbols-rounded">delete_sweep</span> Clear All Data';
                // Refresh from server
                loadDashboardData(false);
            }
        });
    }
}

